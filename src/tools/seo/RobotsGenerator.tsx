import React, { useState } from 'react';
import { Copy, Check, Download } from 'lucide-react';
import { copyToClipboard, downloadText } from '../../utils/formatting';

export const RobotsGenerator: React.FC = () => {
  const [allowAll, setAllowAll] = useState<boolean>(true);
  const [sitemapUrl, setSitemapUrl] = useState<string>('https://zynovexa.com/sitemap.xml');
  const [disallowedPaths, setDisallowedPaths] = useState<string>('/admin/\n/private/\n/api/');
  const [crawlDelay, setCrawlDelay] = useState<string>('');
  const [copied, setCopied] = useState<boolean>(false);

  const generateRobotsTxt = (): string => {
    let lines = ['# Robots.txt generated by Zynovexa', 'User-agent: *'];

    if (allowAll) {
      lines.push('Allow: /');
    }

    if (disallowedPaths.trim()) {
      const paths = disallowedPaths.split('\n').map((p) => p.trim()).filter(Boolean);
      paths.forEach((p) => {
        lines.push(`Disallow: ${p.startsWith('/') ? p : '/' + p}`);
      });
    }

    if (crawlDelay) {
      lines.push(`Crawl-delay: ${crawlDelay}`);
    }

    if (sitemapUrl.trim()) {
      lines.push('');
      lines.push(`Sitemap: ${sitemapUrl.trim()}`);
    }

    return lines.join('\n');
  };

  const robotsOutput = generateRobotsTxt();

  const handleCopy = async () => {
    await copyToClipboard(robotsOutput);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    downloadText(robotsOutput, 'robots.txt');
  };

  return (
    <div className="space-y-6">
      <div className="p-5 bg-white border border-slate-200 rounded-2xl space-y-4">
        <div>
          <label className="block text-xs font-semibold text-slate-700 uppercase tracking-wider mb-1">
            Sitemap URL (Optional)
          </label>
          <input
            type="url"
            value={sitemapUrl}
            onChange={(e) => setSitemapUrl(e.target.value)}
            placeholder="https://example.com/sitemap.xml"
            className="w-full px-3 py-2 border border-slate-200 rounded-lg text-sm text-slate-900 focus:ring-2 focus:ring-blue-600 focus:outline-none"
          />
        </div>

        <div>
          <label className="block text-xs font-semibold text-slate-700 uppercase tracking-wider mb-1">
            Disallowed Paths (One per line)
          </label>
          <textarea
            rows={3}
            value={disallowedPaths}
            onChange={(e) => setDisallowedPaths(e.target.value)}
            className="w-full p-3 font-mono text-xs border border-slate-200 rounded-lg text-slate-900 focus:ring-2 focus:ring-blue-600 focus:outline-none"
          />
        </div>

        <div className="grid grid-cols-1 sm:grid-cols-2 gap-4 pt-2">
          <label className="flex items-center gap-2 text-xs font-semibold text-slate-700 cursor-pointer">
            <input
              type="checkbox"
              checked={allowAll}
              onChange={(e) => setAllowAll(e.target.checked)}
              className="rounded text-blue-600 focus:ring-blue-500"
            />
            <span>Allow All Other Crawlers ("Allow: /")</span>
          </label>

          <div>
            <label className="text-xs font-semibold text-slate-700 block mb-1">
              Crawl Delay (Seconds, optional)
            </label>
            <input
              type="number"
              min="1"
              max="60"
              value={crawlDelay}
              onChange={(e) => setCrawlDelay(e.target.value)}
              placeholder="e.g. 5"
              className="w-full px-3 py-1.5 border border-slate-200 rounded-lg text-xs"
            />
          </div>
        </div>
      </div>

      <div>
        <div className="flex items-center justify-between mb-2">
          <span className="text-xs font-semibold text-slate-700 uppercase tracking-wider">
            Generated robots.txt
          </span>
          <div className="flex items-center gap-2">
            <button
              onClick={handleCopy}
              className="px-3 py-1 bg-white hover:bg-slate-100 border border-slate-200 rounded-md text-xs font-semibold text-slate-700 flex items-center gap-1 cursor-pointer"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Copy className="w-3.5 h-3.5" />}
              {copied ? 'Copied' : 'Copy'}
            </button>
            <button
              onClick={handleDownload}
              className="px-3 py-1 bg-blue-600 hover:bg-blue-700 text-white rounded-md text-xs font-semibold flex items-center gap-1 cursor-pointer"
            >
              <Download className="w-3.5 h-3.5" />
              Download robots.txt
            </button>
          </div>
        </div>
        <textarea
          rows={8}
          readOnly
          value={robotsOutput}
          className="w-full p-4 font-mono text-xs bg-slate-900 text-slate-100 rounded-xl border border-slate-800 focus:outline-none"
        />
      </div>
    </div>
  );
};
